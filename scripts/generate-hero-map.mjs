/**
 * Builds the hero illustration data: Cambodia's 25 province outlines as compact SVG paths.
 *
 *   node scripts/generate-hero-map.mjs
 *
 * Reads public/boundaries/province.geojson (~1 MB) + public/data/seed/provinces.json (names),
 * projects lon/lat to a flat plane, simplifies each ring (Douglas–Peucker) and writes
 * web/src/pages/home/cambodiaMap.ts (a few dozen KB). Re-run only if the boundaries change.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const geo = JSON.parse(readFileSync(path.join(root, "public/boundaries/province.geojson"), "utf8"));
const seed = JSON.parse(readFileSync(path.join(root, "public/data/seed/provinces.json"), "utf8"));
const byCode = new Map(seed.map((p) => [p.code, p]));

const WIDTH = 1000;
const TOLERANCE = 1.1; // in output units; larger = fewer points
const MIN_RING_AREA = 6; // drop specks (tiny islands) smaller than this, in output units²

// Bounds + equirectangular projection corrected for latitude
let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
const rings = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates).flat();
for (const f of geo.features) for (const ring of rings(f.geometry)) for (const [lon, lat] of ring) {
    minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
    minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
}
const kx = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
const scale = WIDTH / ((maxLon - minLon) * kx);
const HEIGHT = Math.ceil((maxLat - minLat) * scale);
const project = ([lon, lat]) => [(lon - minLon) * kx * scale, (maxLat - lat) * scale];

function simplify(pts, tol) {
    if (pts.length < 4) return pts;
    const sq = tol * tol;
    const keep = new Uint8Array(pts.length);
    keep[0] = keep[pts.length - 1] = 1;
    const stack = [[0, pts.length - 1]];
    while (stack.length) {
        const [a, b] = stack.pop();
        const [ax, ay] = pts[a], [bx, by] = pts[b];
        const dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy || 1;
        let max = 0, idx = -1;
        for (let i = a + 1; i < b; i++) {
            const t = Math.max(0, Math.min(1, ((pts[i][0] - ax) * dx + (pts[i][1] - ay) * dy) / len));
            const ex = ax + t * dx - pts[i][0], ey = ay + t * dy - pts[i][1];
            const d = ex * ex + ey * ey;
            if (d > max) { max = d; idx = i; }
        }
        if (max > sq && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
    }
    return pts.filter((_, i) => keep[i]);
}

const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => { const [nx, ny] = pts[(i + 1) % pts.length]; return s + x * ny - nx * y; }, 0)) / 2;
const r1 = (n) => Math.round(n * 10) / 10;

const provinces = geo.features.map((f) => {
    const code = String(f.properties.ADM1_PCODE).replace(/^KH/, "");
    const meta = byCode.get(code);
    if (!meta) throw new Error(`No seed entry for province code ${code}`);
    let d = "";
    let biggest = { a: 0, pts: [] };
    for (const ring of rings(f.geometry)) {
        const pts = simplify(ring.map(project), TOLERANCE);
        const a = area(pts);
        if (pts.length < 4 || a < MIN_RING_AREA) continue;
        if (a > biggest.a) biggest = { a, pts };
        d += "M" + pts.slice(0, -1).map(([x, y]) => `${r1(x)} ${r1(y)}`).join("L") + "Z";
    }
    // Label anchor: area-weighted centroid of the largest ring (stays inside the shape for these outlines)
    let cx = 0, cy = 0, A = 0;
    const p = biggest.pts;
    for (let i = 0; i < p.length - 1; i++) {
        const c = p[i][0] * p[i + 1][1] - p[i + 1][0] * p[i][1];
        A += c; cx += (p[i][0] + p[i + 1][0]) * c; cy += (p[i][1] + p[i + 1][1]) * c;
    }
    return { code, id: meta.id, en: meta.name_en, km: meta.name_km, cx: r1(cx / (3 * A)), cy: r1(cy / (3 * A)), d };
}).sort((a, b) => a.code.localeCompare(b.code));

const out = `// Generated by scripts/generate-hero-map.mjs from public/boundaries/province.geojson — do not edit by hand.
export interface HeroProvince {
    code: string;
    id: number;
    en: string;
    km: string;
    /** Label anchor in viewBox units */
    cx: number;
    cy: number;
    /** SVG path data */
    d: string;
}

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export const PROVINCES: HeroProvince[] = ${JSON.stringify(provinces, null, 1)};
`;
const file = path.join(root, "web/src/pages/home/cambodiaMap.ts");
writeFileSync(file, out);
const points = provinces.reduce((s, p) => s + (p.d.match(/L/g)?.length ?? 0), 0);
console.log(`Wrote ${path.relative(root, file)}: ${provinces.length} provinces, ~${points} points, ${(out.length / 1024).toFixed(1)} KB, viewBox 0 0 ${WIDTH} ${HEIGHT}`);
